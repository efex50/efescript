const BIN: &str = env!("CARGO_BIN_EXE_efescript");

fn check_golden(name: &str, got: &str) {
    let path = fixture(name);
    if std::env::var_os("EFE_BLESS").is_some() {
        std::fs::write(&path, got).unwrap();
        return;
    }
    let want = std::fs::read_to_string(&path).unwrap_or_else(|e| panic!("{}: {e} (EFE_BLESS=1 creates it)", path.display()));
    if want != got {
        let at = want.lines().zip(got.lines()).position(|(a, b)| a != b).map(|i| i + 1).unwrap_or(want.lines().count().min(got.lines().count()) + 1);
        panic!("{name} differs from the generator output at line {at}; review the change, then EFE_BLESS=1 to update");
    }
}

#[test]
fn rust_bindings_match_golden() {
    let out = rustgen::generate(&fixture_index()).unwrap();
    assert!(out.starts_with("// @generated by `efescript api-export --rust`"));
    assert!(out.contains(&format!("fnv1a64:{:016x}", fixture_index().hash())));
    check_golden("guest_test.api.rs", &out);
}

#[test]
fn c_header_matches_golden() {
    let out = cgen::generate(&fixture_index()).unwrap();
    assert!(out.starts_with("/* @generated by `efescript api-export --c`"));
    check_golden("guest_test.efe_api.h", &out);
}

#[test]
fn output_is_deterministic_and_input_order_free() {
    let ix = fixture_index();
    assert_eq!(rustgen::generate(&ix).unwrap(), rustgen::generate(&ix).unwrap());
    // A re-read of the written index gives the same bindings.
    let again = ApiIndex::from_json(&ix.to_json()).unwrap();
    assert_eq!(rustgen::generate(&again).unwrap(), rustgen::generate(&ix).unwrap());
    assert_eq!(cgen::generate(&again).unwrap(), cgen::generate(&ix).unwrap());
}

#[test]
fn cli_writes_the_golden_files_and_merges_inputs() {
    let dir = std::env::temp_dir().join(format!("efe-bindgen-{}", std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    let efapi = fixture("guest_test.efapi");
    let efapi = efapi.to_str().unwrap();
    let rs = dir.join("api.rs");
    // The same input twice: identical entries are kept once (ApiIndex::merge).
    let o = Command::new(BIN).args(["api-export", "--rust", efapi, efapi, "-o"]).arg(&rs).output().unwrap();
    assert!(o.status.success(), "{}", String::from_utf8_lossy(&o.stderr));
    assert_eq!(std::fs::read_to_string(&rs).unwrap(), std::fs::read_to_string(fixture("guest_test.api.rs")).unwrap());
    let o = Command::new(BIN).args(["api-export", "--c", efapi]).output().unwrap();
    assert!(o.status.success());
    assert_eq!(String::from_utf8(o.stdout).unwrap(), std::fs::read_to_string(fixture("guest_test.efe_api.h")).unwrap());
    // No input and a missing input are errors with a message, not a panic.
    let o = Command::new(BIN).args(["api-export", "--rust"]).output().unwrap();
    assert_eq!(o.status.code(), Some(2));
    assert!(String::from_utf8_lossy(&o.stderr).contains("needs at least one"));
    let o = Command::new(BIN).args(["api-export", "--c", "/nonexistent.efapi"]).output().unwrap();
    assert_eq!(o.status.code(), Some(2));
    let _ = std::fs::remove_dir_all(&dir);
}

/// An index with one namespace and the given functions.
fn index_with(f: impl FnOnce(&mut ApiIndex)) -> ApiIndex {
    let mut ix = ApiIndex { game: "t".into(), ..Default::default() };
    ix.namespaces = vec![NamespaceInfo { name: "g".into(), version: 1, owner: "t".into(), doc: "g".into() }];
    f(&mut ix);
    ix.sort();
    ix
}

fn both(ix: &ApiIndex) -> (String, String) {
    (rustgen::generate(ix).unwrap_err().to_string(), cgen::generate(ix).map(|_| String::new()).unwrap_or_else(|e| e.to_string()))
}

#[test]
fn names_rust_cannot_spell_are_errors() {
    for bad in ["self", "crate", "super", "Self", "_"] {
        let ix = index_with(|ix| ix.functions.push(HostFn::new("g", bad).doc("d")));
        let e = rustgen::generate(&ix).unwrap_err().to_string();
        assert!(e.contains(&format!("`{bad}`")) && e.contains("cannot be used as a Rust name"), "{e}");
    }
    // A keyword parameter name is escaped, not an error.
    let ix = index_with(|ix| ix.functions.push(HostFn::new("g", "f").doc("d").param("loop", ApiType::I32)));
    assert!(rustgen::generate(&ix).unwrap().contains("r#loop: i32"));
    // A struct that would shadow a primitive, a reserved name, and a mod component.
    for name in ["u32", "Entity"] {
        let ix = index_with(|ix| ix.types.push(StructDesc::new(name, 4, 4).field(FieldDesc::new("a", 0, Prim::U32, 1))));
        assert!(rustgen::generate(&ix).is_err(), "{name}");
    }
}

#[test]
fn several_results_are_an_error() {
    let ix = index_with(|ix| ix.functions.push(HostFn::new("g", "two").doc("d").result("a", ApiType::I32).result("b", ApiType::I32)));
    let (r, c) = both(&ix);
    assert!(r.contains("g.two: 2 results"), "{r}");
    assert!(c.contains("g.two: 2 results"), "{c}");
}

#[test]
fn name_collisions_are_errors() {
    // A namespace module and a struct with the same name at the top level.
    let ix = index_with(|ix| ix.types.push(StructDesc::new("g", 4, 4).field(FieldDesc::new("a", 0, Prim::U32, 1))));
    assert!(rustgen::generate(&ix).unwrap_err().to_string().contains("collides"));
    // Two C names that meet: `g.a_b` and `g.a` + `b`... `g_a_b` from namespace g.a function b and g function a_b.
    let ix = index_with(|ix| {
        ix.namespaces.push(NamespaceInfo { name: "g.a".into(), version: 1, owner: "t".into(), doc: "d".into() });
        ix.functions.push(HostFn::new("g", "a_b").doc("d"));
        ix.functions.push(HostFn::new("g.a", "b").doc("d"));
    });
    assert!(rustgen::generate(&ix).is_ok());
    assert!(cgen::generate(&ix).unwrap_err().to_string().contains("g_a_b"));
    // Parameter names that meet after lowering `str`.
    let ix = index_with(|ix| ix.functions.push(HostFn::new("g", "f").doc("d").param("s", ApiType::Str).param("s_ptr", ApiType::I32)));
    let (r, c) = both(&ix);
    assert!(r.contains("collide") && c.contains("collide"), "{r} / {c}");
}

#[test]
fn invalid_indices_are_errors_not_code() {
    // A function in a namespace the index does not list.
    let ix = index_with(|ix| ix.functions.push(HostFn::new("nope", "f").doc("d")));
    assert!(rustgen::generate(&ix).unwrap_err().to_string().contains("invalid API index"));
    assert!(cgen::generate(&ix).unwrap_err().to_string().contains("invalid API index"));
}

#[test]
fn doc_text_cannot_break_the_output() {
    let ix = index_with(|ix| {
        ix.functions.push(HostFn::new("g", "f").doc("    indented\n```\ncode */ and /* nested"));
    });
    let r = rustgen::generate(&ix).unwrap();
    assert!(!r.contains("\n/// ```") && !r.contains("///     indented"));
    let c = cgen::generate(&ix).unwrap();
    assert_eq!(c.matches("*/").count(), c.matches("/*").count() + 0, "comment delimiters stay balanced:\n{c}");
}

fn tool(name: &str) -> bool {
    Command::new(name).arg("--version").output().map(|o| o.status.success()).unwrap_or(false)
}

#[test]
fn c_header_is_valid_c_and_cpp() {
    let h = fixture("guest_test.efe_api.h");
    let mut ran = false;
    for (cc, lang, std) in [("gcc", "c", "-std=c11"), ("g++", "c++", "-std=gnu++17"), ("clang", "c", "-std=c11")] {
        if !tool(cc) {
            continue;
        }
        let o = Command::new(cc)
            .args([std, "-fsyntax-only", "-Wall", "-Wextra", "-Wno-attributes", "-Wno-unused", "-DEFE_API_IMPLEMENTATION", "-x", lang])
            .arg(&h)
            .output()
            .unwrap();
        assert!(o.status.success(), "{cc} rejects the header (static asserts check the layouts):\n{}", String::from_utf8_lossy(&o.stderr));
        ran = true;
    }
    if !ran {
        eprintln!("SKIPPED: no C compiler (gcc, g++, clang) found");
    }
}

#[test]
fn c_provide_records_match_the_format() {
    // Native gcc compiles the example; the records are read back from its ELF section. That
    // checks efe_guest.h's byte layout; it needs no wasm toolchain.
    if !tool("gcc") || !tool("objcopy") {
        eprintln!("SKIPPED: gcc and objcopy are needed to check the C records natively");
        return;
    }
    let dir = std::env::temp_dir().join(format!("efe-crec-{}", std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    let obj = dir.join("mod.o");
    let inc = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../efe-guest/include");
    let o = Command::new("gcc")
        .args(["-std=gnu11", "-Wall", "-Wno-attributes", "-c"])
        .arg("-I").arg(&inc).arg("-I").arg(fixture("."))
        .arg(fixture("guest_c/mod.c")).arg("-o").arg(&obj)
        .output().unwrap();
    assert!(o.status.success(), "{}", String::from_utf8_lossy(&o.stderr));
    let dump = |section: &str| {
        let out = dir.join(format!("{section}.bin"));
        let o = Command::new("objcopy").args(["-O", "binary", &format!("--only-section=.custom_section.{section}")]).arg(&obj).arg(&out).output().unwrap();
        assert!(o.status.success());
        std::fs::read(&out).unwrap()
    };
    let recs = decode_provide(&dump("efe.provide")).expect("records decode");
    assert_records(&recs);
    assert!(recs.iter().any(|r| matches!(r, Rec::Func { name, params, results, .. } if name == "noop" && params.is_empty() && results.is_empty())));
    assert_eq!(dump("efe.api"), fixture_index().hash().to_le_bytes());
    let _ = std::fs::remove_dir_all(&dir);
}
